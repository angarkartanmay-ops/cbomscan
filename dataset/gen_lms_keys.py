#!/usr/bin/env python3
"""Generate throwaway LMS/HSS public keys for the dataset, straight from RFC 8554.

This is our own implementation of RFC 8554 key generation (sections 4.1-4.3, 5.2-5.3 and
Appendix A seed derivation), single-level HSS. It has NOT been cross-checked against a reference
verifier in this environment (running third-party native code was not permitted here), so these
keys are used only as realistic-looking public-key *structures* (type codes, 16-byte I, a 32-byte
hash T[1]) for testing structure detection. Seeds are fixed so the output is reproducible; the
private keys are therefore public and must never protect anything.

Writes dataset/support/pqc/lms_pubkeys.h.
"""

import hashlib
import struct
import sys
from pathlib import Path

D_PBLC, D_LEAF, D_INTR = 0x8080, 0x8282, 0x8383   # RFC 8554 section 4.3, 5.3, 5.3
H = lambda *parts: hashlib.sha256(b"".join(parts)).digest()
u32 = lambda x: struct.pack(">I", x)
u16 = lambda x: struct.pack(">H", x)

LMS_H = {5: 5, 6: 10, 7: 15, 8: 20, 9: 25}                 # LMS typecode -> tree height
OTS = {1: (1, 265), 2: (2, 133), 3: (4, 67), 4: (8, 34)}   # LMOTS typecode -> (w, p) for SHA-256 N32


def ots_pub_hash(I, q, ots_type, seed):
    w, p = OTS[ots_type]
    ys = []
    for i in range(p):
        x = H(I, u32(q), u16(i), b"\xff", seed)              # Appendix A
        tmp = x
        for j in range((1 << w) - 1):
            tmp = H(I, u32(q), u16(i), bytes([j]), tmp)
        ys.append(tmp)
    return H(I, u32(q), u16(D_PBLC), *ys)


def lms_public_key(lms_type, ots_type, I, seed):
    h = LMS_H[lms_type]
    t = {}
    for q in range(1 << h):
        r = (1 << h) + q
        t[r] = H(I, u32(r), u16(D_LEAF), ots_pub_hash(I, q, ots_type, seed))
    for r in range((1 << h) - 1, 0, -1):
        t[r] = H(I, u32(r), u16(D_INTR), t[2 * r], t[2 * r + 1])
    return u32(lms_type) + u32(ots_type) + I + t[1]


SETS = [("h5_w8", 5, 4), ("h5_w1", 5, 1), ("h5_w2", 5, 2), ("h10_w4", 6, 3)]


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).parent / "support/pqc/lms_pubkeys.h")
    lines = ["/* Generated by dataset/gen_lms_keys.py (own RFC 8554 implementation, deterministic throwaway keys). */"]
    for name, lt, ot in SETS:
        I = H(b"cbomscan-lms-I-" + name.encode())[:16]
        seed = H(b"cbomscan-lms-seed-" + name.encode())
        pk = u32(1) + lms_public_key(lt, ot, I, seed)      # HSS: levels = 1, then the LMS public key
        body = ",".join(f"0x{b:02x}" for b in pk)
        lines.append(f"static const unsigned char lms_pub_{name}[{len(pk)}] = {{{body}}};")
        print(f"{name}: lms_type={lt} ots_type={ot} {len(pk)} bytes  {pk.hex()[:48]}...")
    out.write_text("\n".join(lines) + "\n", newline="\n")


if __name__ == "__main__":
    main()
